# ── Data ──────────────────────────────────────────────────────────────────────

class Data:
    """Daily precipitation and evaporation time series."""

    def __init__(self, prec: pd.Series, evap: pd.Series):
        self.prec = prec
        self.evap = evap

    @classmethod
    def from_csv(cls, prec_path, evap_path):
        prec = pd.read_csv(
            prec_path, parse_dates=True, index_col=[0],
            sep=";", usecols=[0, 2], dayfirst=True,
        ).resample("D").sum().squeeze()
        evap = pd.read_csv(
            evap_path, parse_dates=True, index_col=[0],
            sep=";", dayfirst=True,
        ).squeeze()
        return cls(prec, evap)

    @classmethod
    def default(cls):
        return cls.from_csv(_VLAB_DIR / "prec.csv", _VLAB_DIR / "evap.csv")


# ── Epikarst ──────────────────────────────────────────────────────────────────

class Epikarst:
    """Soil/epikarst recharge model (FlexModelFrac by default)."""

    def __init__(self, n_tiles: int = 5):
        self.n_tiles = n_tiles
        self._model = FlexModelFrac()

    def simulate(self, data: Data, rch_params) -> np.ndarray:
        """
        Simulate total recharge (slow + quick) for the study period.

        Parameters
        ----------
        data : Data
        rch_params : array-like, shape (7,)
            [srmax, lp, ks, gamma, simax, kv, omega]

        Returns
        -------
        rch_ts : np.ndarray, shape (len(data.prec),), mm/d
        """
        n = len(data.prec)
        prec_ml = np.tile(data.prec.values.ravel(), self.n_tiles)
        evap_ml = np.tile(data.evap.values.ravel(), self.n_tiles)
        rch_slow, rch_quick = self._model.simulate(
            prec=prec_ml, evap=evap_ml, p=np.array(rch_params)
        )
        return (rch_slow + rch_quick)[n * (self.n_tiles - 1):]


# ── Parameter groups ──────────────────────────────────────────────────────────

class RechargeParams:
    """
    Recharge model parameter group.

    Parameters
    ----------
    stochastic : bool
        If True, parameters are sampled via LHS. If False, fixed values are used.
    values : dict, optional
        Override default fixed values. Used when stochastic=False.
    bounds : dict, optional
        Override default sampling bounds. Used when stochastic=True.
        Each entry should be a (low, high) tuple.
    """

    NAMES = ["srmax", "lp", "ks", "gamma", "simax", "kv", "omega"]
    _DEFAULTS = {
        "srmax": 250., "lp": 0.25, "ks": 1000.,
        "gamma": 2., "simax": 1., "kv": 5., "omega": 0.2,
    }
    _BOUNDS = {
        "srmax": (100., 500.), "lp": (0.1, 0.8), "ks": (100., 5000.),
        "gamma": (1., 5.), "simax": (0.5, 10.), "kv": (0.1, 10.),
        "omega": (0.1, 0.9),
    }

    def __init__(self, stochastic=True, values=None, bounds=None):
        self.stochastic = stochastic
        self.values = {**self._DEFAULTS, **(values or {})}
        self.bounds = {**self._BOUNDS, **(bounds or {})}
        self._samples = None


class NetworkStructure:
    """
    Network structure parameter group (stochastic: sks_seed only).

    The inlet/outlet counts, seeds, and fracture family definitions are
    fixed properties of the system — they can only be changed by passing
    a different NetworkStructure to a different System instance.

    Parameters
    ----------
    stochastic : bool
        If True, sks_seed is sampled via LHS over sks_range.
    values : dict, optional
        Override default fixed value for sks_seed.
    bounds : dict, optional
        Override sampling range, e.g. {"sks_seed": (0, 50000)}.
    n_inlets : int
        Number of inlets (sinkholes) generated by pyKasso.
    inlets_seed : int
        Random seed for inlet placement.
    outlets_seed : int
        Random seed for outlet placement.
    fracture_families : dict, optional
        pyKasso fracture family definitions. None uses the built-in default.
    """

    NAMES = ["sks_seed"]
    _DEFAULTS = {"sks_seed": 12345}
    _BOUNDS    = {"sks_seed": (0, 99999)}

    def __init__(self, stochastic=True, values=None, bounds=None,
                 n_inlets=5, inlets_seed=456, outlets_seed=7,
                 fracture_families=None):
        self.stochastic = stochastic
        self.values = {**self._DEFAULTS, **(values or {})}
        self.bounds = {**self._BOUNDS, **(bounds or {})}
        self._samples = None
        # fixed structural config
        self.n_inlets = n_inlets
        self.inlets_seed = inlets_seed
        self.outlets_seed = outlets_seed
        self.fracture_families = fracture_families if fracture_families is not None \
            else _DEFAULT_FRACTURES


